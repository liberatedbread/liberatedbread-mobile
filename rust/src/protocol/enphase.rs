//! Digi XBee 3 BLE authentication and relay framing for Enphase Ensemble gear.
//!
//! The unlock is SRP-6a over the RFC 5054 1024-bit group with SHA-256. The
//! encrypted channel is AES-256-CTR, with independent client/server nonces.
//! Enphase's own provisioning payloads stay out of this file: it proves the
//! link and carries the bytes, without issuing a reset or changing the site.

use aes::cipher::{BlockCipherEncrypt, KeyInit};
use num_bigint::BigUint;
use sha2::{Digest, Sha256};

use crate::error::ProtocolError;

const EPHEMERAL_BYTES: usize = 128;
const NONCE_BYTES: usize = 12;
const COUNTER_BYTES: usize = 16;
const PRIME_HEX: &str = concat!(
    "EEAF0AB9ADB38DD69C33F80AFA8FC5E86072618775FF3C0B9EA2314C",
    "9C256576D674DF7496EA81D3383B4813D692C6E0E0D5D8E250B98BE4",
    "8E495C1D6089DAD15DC7D7B46154D6B6CE8EF4AD69B15D4982559B29",
    "7BCF1885C529F566660E57EC68EDBC3C05726CC02FD4CBF4976EAA9A",
    "FD5138FE8376435B9FC61D2FC0EB06E3"
);

#[derive(Debug, Clone)]
pub struct EnphaseProofDto {
    pub m1: Vec<u8>,
    pub session_key: Vec<u8>,
    pub expected_m2: Vec<u8>,
}

#[derive(Debug, Clone)]
pub struct XBeeFrameDto {
    pub frame_type: u8,
    pub step: u8,
    pub payload: Vec<u8>,
}

fn invalid(reason: impl Into<String>) -> ProtocolError {
    ProtocolError::MalformedReply(reason.into())
}

fn sha256(parts: &[&[u8]]) -> Vec<u8> {
    let mut hash = Sha256::new();
    for part in parts {
        hash.update(part);
    }
    hash.finalize().to_vec()
}

fn prime() -> BigUint {
    BigUint::parse_bytes(PRIME_HEX.as_bytes(), 16).expect("the RFC 5054 prime is valid")
}

fn generator() -> BigUint {
    BigUint::from(2u8)
}

fn padded(value: &BigUint) -> Vec<u8> {
    let bytes = value.to_bytes_be();
    let mut out = vec![0; EPHEMERAL_BYTES.saturating_sub(bytes.len())];
    out.extend_from_slice(&bytes);
    out
}

/// The one-time client public value A. The private scalar is exactly 32 bytes,
/// generated by the caller so tests and live connections use the same path.
pub fn enphase_client_ephemeral(private_key: Vec<u8>) -> Result<Vec<u8>, ProtocolError> {
    if private_key.len() != 32 {
        return Err(invalid("the SRP private scalar must be 32 bytes"));
    }
    let a = BigUint::from_bytes_be(&private_key);
    if a == BigUint::from(0u8) {
        return Err(invalid("the SRP private scalar must not be zero"));
    }
    Ok(padded(&generator().modpow(&a, &prime())))
}

/// Process B + salt into M1, the shared session key and the M2 the server
/// must prove. A wrong proof is rejected by the caller, never accepted as a
/// successful pairing.
pub fn enphase_process_challenge(
    private_key: Vec<u8>,
    public_a: Vec<u8>,
    salt: Vec<u8>,
    public_b: Vec<u8>,
    username: String,
    password: String,
) -> Result<EnphaseProofDto, ProtocolError> {
    if private_key.len() != 32 || public_a.len() != EPHEMERAL_BYTES {
        return Err(invalid("bad SRP client key lengths"));
    }
    if salt.is_empty() || public_b.len() != EPHEMERAL_BYTES {
        return Err(invalid("bad SRP server key lengths"));
    }
    let n = prime();
    let g = generator();
    let a = BigUint::from_bytes_be(&private_key);
    let b = BigUint::from_bytes_be(&public_b) % &n;
    if b == BigUint::from(0u8) {
        return Err(invalid("the server offered B mod N = 0"));
    }
    let k = BigUint::from_bytes_be(&sha256(&[&n.to_bytes_be(), &padded(&g)]));
    let u = BigUint::from_bytes_be(&sha256(&[&public_a, &public_b]));
    if u == BigUint::from(0u8) {
        return Err(invalid("the server challenge has u = 0"));
    }
    let identity_hash = sha256(&[format!("{username}:{password}").as_bytes()]);
    let x = BigUint::from_bytes_be(&sha256(&[&salt, &identity_hash]));
    let v = g.modpow(&x, &n);
    let kv = (k * v) % &n;
    let base = if b >= kv { b - kv } else { &n - (kv - b) };
    let s = base.modpow(&(a + u * x), &n);
    let session_key = sha256(&[&s.to_bytes_be()]);

    let n_hash = sha256(&[&n.to_bytes_be()]);
    let g_hash = sha256(&[&g.to_bytes_be()]);
    let xor: Vec<u8> = n_hash.iter().zip(&g_hash).map(|(a, b)| a ^ b).collect();
    let username_hash = sha256(&[username.as_bytes()]);
    let m1 = sha256(&[
        &xor,
        &username_hash,
        &salt,
        &public_a,
        &public_b,
        &session_key,
    ]);
    let expected_m2 = sha256(&[&public_a, &m1, &session_key]);
    Ok(EnphaseProofDto {
        m1,
        session_key,
        expected_m2,
    })
}

/// One API frame: delimiter, big-endian payload length, frame type, step (or
/// frame ID), payload and the two's-complement checksum.
pub fn xbee_encode_frame(frame_type: u8, step: u8, payload: Vec<u8>) -> Vec<u8> {
    let length = 2 + payload.len();
    let mut out = vec![
        0x7e,
        ((length >> 8) & 0xff) as u8,
        (length & 0xff) as u8,
        frame_type,
        step,
    ];
    out.extend_from_slice(&payload);
    let sum = out[3..]
        .iter()
        .fold(0u8, |sum, byte| sum.wrapping_add(*byte));
    out.push(0xff - sum);
    out
}

/// Decode exactly one complete API frame, rejecting truncation, trailing
/// bytes and a bad checksum rather than parsing around them.
pub fn xbee_decode_frame(bytes: Vec<u8>) -> Result<XBeeFrameDto, ProtocolError> {
    if bytes.len() < 6 || bytes[0] != 0x7e {
        return Err(invalid("not an XBee API frame"));
    }
    let payload_len = ((bytes[1] as usize) << 8) | bytes[2] as usize;
    if payload_len < 2 || bytes.len() != payload_len + 4 {
        return Err(invalid("the XBee frame length does not match its payload"));
    }
    let sum = bytes[3..bytes.len() - 1]
        .iter()
        .fold(0u8, |sum, byte| sum.wrapping_add(*byte));
    if 0xff - sum != bytes[bytes.len() - 1] {
        return Err(invalid("the XBee checksum does not match"));
    }
    Ok(XBeeFrameDto {
        frame_type: bytes[3],
        step: bytes[4],
        payload: bytes[5..bytes.len() - 1].to_vec(),
    })
}

/// Apply the continuous AES-256-CTR stream at an arbitrary byte offset. This
/// keeps the Dart frame assembler stateless: it carries only the TX/RX offsets
/// between notifications, while Rust owns the block cipher and endianness.
pub fn enphase_apply_cipher(
    key: Vec<u8>,
    nonce: Vec<u8>,
    offset: u64,
    mut data: Vec<u8>,
) -> Result<Vec<u8>, ProtocolError> {
    if key.len() != 32 || nonce.len() != NONCE_BYTES {
        return Err(invalid("bad AES key or nonce length"));
    }
    let block = offset / COUNTER_BYTES as u64;
    let skip = (offset % COUNTER_BYTES as u64) as usize;
    let counter = ((block + 1) as u32).to_be_bytes();
    let mut iv = nonce;
    iv.extend_from_slice(&counter);
    let key: [u8; 32] = key.try_into().expect("the AES key length was checked");
    let mut counter_block: [u8; 16] = iv.try_into().expect("the IV length was checked");
    let cipher = aes::Aes256::new((&key).into());
    let mut stream = vec![0; skip];
    stream.extend_from_slice(&data);
    for chunk in stream.chunks_mut(counter_block.len()) {
        let mut mask = counter_block;
        cipher.encrypt_block((&mut mask).into());
        for (output, mask_byte) in chunk.iter_mut().zip(mask.iter()) {
            *output ^= mask_byte;
        }
        for byte in counter_block.iter_mut().rev() {
            if *byte == 0xff {
                *byte = 0;
            } else {
                *byte += 1;
                break;
            }
        }
    }
    data.copy_from_slice(&stream[skip..]);
    Ok(data)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(value: &str) -> Vec<u8> {
        let compact: String = value.chars().filter(|c| !c.is_whitespace()).collect();
        (0..compact.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&compact[i..i + 2], 16).unwrap())
            .collect()
    }

    const PRIVATE: &str = "60975527035cf2ad1989806f0407210bc81edc04e2762a56afd529ddda2d4393";
    const PUBLIC_A: &str = concat!(
        "61d5e490f6f1b79547b0704c436f523dd0e560f0c64115bb72557ec44352e890",
        "3211c04692272d8b2d1a5358a2cf1b6e0bfcf99f921530ec8e39356179eae45e",
        "42ba92aeaced825171e1e8b9af6d9c03e1327f44be087ef06530e69f66615261",
        "eef54073ca11cf5858f0edfdfe15efeab349ef5d76988a3672fac47b0769447b"
    );
    const PUBLIC_B: &str = concat!(
        "439b7630ec82c94d3bbd466a068d663a40b8d5b1d9b006ba43f5d715498088cc",
        "a8547bbe3de6406c79f15ffa7356bc93580e478322daf8b2d014347859234f01",
        "555c457ab8b7f214875224fc9bfd07a68f37bad4d74bc8467ce10ea39301d360",
        "4e91fff5f881d52c558187e68fac3268df2897307da5c58a8c667e0fa8dc837e"
    );
    const SALT: &str = "beb25379d1a8581eb5a727673a2441ee";
    const SESSION_KEY: &str = "febac740e997507c1c7df7690bac49a97f84ecda99ceb047c575b58e160c477b";
    const M1: &str = "51d0af1793f2921cfc4a41bc5134605a7bf89a3497aed7c29ed6c56ae709037f";
    const M2: &str = "2f6b44340bf8dc05148b6b3ae1d70b6a896588ba6b2c16d8aec619d2cc57653f";

    #[test]
    fn srp_sha256_vector_matches_the_public_client_proof() {
        let proof = enphase_process_challenge(
            hex(PRIVATE),
            hex(PUBLIC_A),
            hex(SALT),
            hex(PUBLIC_B),
            "alice".into(),
            "password123".into(),
        )
        .unwrap();
        assert_eq!(proof.m1, hex(M1));
        assert_eq!(proof.session_key, hex(SESSION_KEY));
        assert_eq!(proof.expected_m2, hex(M2));
    }

    #[test]
    fn the_public_ephemeral_has_the_wire_width() {
        let public = enphase_client_ephemeral(hex(PRIVATE)).unwrap();
        assert_eq!(public.len(), EPHEMERAL_BYTES);
        assert_eq!(public, hex(PUBLIC_A));
    }

    #[test]
    fn a_server_ephemeral_is_refused_modulo_n() {
        for public_b in [vec![0; EPHEMERAL_BYTES], padded(&prime())] {
            let error = enphase_process_challenge(
                hex(PRIVATE),
                hex(PUBLIC_A),
                hex(SALT),
                public_b,
                "alice".into(),
                "password123".into(),
            )
            .unwrap_err();
            assert!(error.to_string().contains("B mod N = 0"));
        }
    }

    #[test]
    fn api_frames_round_trip_and_reject_a_changed_checksum() {
        let frame = xbee_encode_frame(0x2d, 1, vec![0, 4, 0]);
        let decoded = xbee_decode_frame(frame.clone()).unwrap();
        assert_eq!(decoded.frame_type, 0x2d);
        assert_eq!(decoded.step, 1);
        assert_eq!(decoded.payload, [0, 4, 0]);

        let mut damaged = frame;
        let last = damaged.len() - 1;
        damaged[last] ^= 1;
        assert!(xbee_decode_frame(damaged).is_err());
    }

    #[test]
    fn cipher_round_trip_is_symmetric() {
        let key = hex(SESSION_KEY);
        let nonce = hex("00112233445566778899aabb");
        let input = vec![1, 2, 3, 4];
        let encrypted = enphase_apply_cipher(key.clone(), nonce.clone(), 0, input.clone()).unwrap();
        let decrypted = enphase_apply_cipher(key, nonce, 0, encrypted).unwrap();
        assert_eq!(decrypted, input);
    }

    #[test]
    fn cipher_offsets_compose_across_notification_boundaries() {
        let key = hex(SESSION_KEY);
        let nonce = hex("00112233445566778899aabb");
        let plain = b"an encrypted relay frame, followed by another one";
        let whole = enphase_apply_cipher(key.clone(), nonce.clone(), 0, plain.to_vec()).unwrap();
        let mut split = Vec::new();
        split.extend(
            enphase_apply_cipher(key.clone(), nonce.clone(), 0, plain[..7].to_vec()).unwrap(),
        );
        split.extend(enphase_apply_cipher(key, nonce, 7, plain[7..].to_vec()).unwrap());
        assert_eq!(whole, split);
        assert_eq!(
            whole,
            hex("d3798a7f1928811334c2a5e5788b43d91311e6c0ab4bb60ed9fa1e87f55e2c94ab7e2ca91da2d2b1289330a2c109ec5db9")
        );

        let recovered =
            enphase_apply_cipher(hex(SESSION_KEY), hex("00112233445566778899aabb"), 0, whole)
                .unwrap();
        assert_eq!(recovered, plain);
    }

    #[test]
    fn malformed_srp_frame_and_cipher_inputs_are_rejected() {
        assert!(enphase_client_ephemeral(vec![0; 31]).is_err());
        assert!(enphase_client_ephemeral(vec![0; 32]).is_err());
        assert!(enphase_process_challenge(
            hex(PRIVATE),
            Vec::new(),
            hex(SALT),
            hex(PUBLIC_B),
            "alice".into(),
            "password123".into(),
        )
        .is_err());
        assert!(enphase_process_challenge(
            hex(PRIVATE),
            hex(PUBLIC_A),
            Vec::new(),
            hex(PUBLIC_B),
            "alice".into(),
            "password123".into(),
        )
        .is_err());

        assert!(xbee_decode_frame(vec![0; 6]).is_err());
        let mut truncated = xbee_encode_frame(0x2d, 1, vec![0, 4, 0]);
        truncated.pop();
        assert!(xbee_decode_frame(truncated).is_err());
        assert!(enphase_apply_cipher(vec![0; 31], vec![0; 12], 0, Vec::new()).is_err());
    }

    #[test]
    fn the_cipher_counter_carries_without_losing_stream_alignment() {
        let key = hex(SESSION_KEY);
        let nonce = hex("00112233445566778899aabb");
        let offset = 254 * COUNTER_BYTES as u64;
        let whole = enphase_apply_cipher(key.clone(), nonce.clone(), offset, vec![7; 32]).unwrap();
        let first = enphase_apply_cipher(key.clone(), nonce.clone(), offset, vec![7; 16]).unwrap();
        let second = enphase_apply_cipher(key, nonce, offset + 16, vec![7; 16]).unwrap();
        assert_eq!(whole, [first, second].concat());
    }
}
